#!/usr/bin/env python3
"""Generate a Track 1 format-valid baseline reconstruction.

This is a submission plumbing baseline, not a vision/reconstruction model. It writes the
per-episode `.npz` files and object meshes required by the NVIDIA V2D Track 1 packer so the
repo can validate the full Kaggle submission path before real reconstruction work begins.

Inputs:
  manifests/track1_required_episodes.json

Outputs by default:
  ../v2d-challenge/generated/track1_format_baseline/
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import trimesh


def rotation_z(theta: float) -> np.ndarray:
    c, s = np.cos(theta), np.sin(theta)
    return np.array([[c, -s, 0.0], [s, c, 0.0], [0.0, 0.0, 1.0]], dtype=np.float64)


def make_lumpy_mesh(episode: int) -> trimesh.Trimesh:
    """Create a deterministic non-degenerate placeholder mesh for one episode."""
    mesh = trimesh.creation.icosphere(subdivisions=2, radius=0.08)
    vertices = np.asarray(mesh.vertices, dtype=np.float64).copy()

    # Break primitive-sphere symmetry without introducing randomness or degeneracy.
    x, y, z = vertices[:, 0], vertices[:, 1], vertices[:, 2]
    phase = episode * 0.37
    scale = 1.0 + 0.18 * np.sin(7.0 * x + phase) + 0.11 * np.cos(5.0 * y - 0.5 * phase)
    vertices[:, 0] = 1.25 * x * scale
    vertices[:, 1] = 0.85 * y * (1.0 + 0.06 * np.sin(episode + 9.0 * z))
    vertices[:, 2] = 0.65 * z * (1.0 + 0.08 * np.cos(episode - 4.0 * x))
    vertices += np.array([0.0, 0.0, 0.04], dtype=np.float64)

    return trimesh.Trimesh(vertices=vertices, faces=np.asarray(mesh.faces), process=True)


def write_episode(out_dir: Path, episode: int, required_t: int) -> None:
    pose = np.zeros((required_t, 136), dtype=np.float32)
    scales = np.ones(68, dtype=np.float32)
    shape = np.zeros(45, dtype=np.float32)

    object_rotation = np.repeat(np.eye(3, dtype=np.float32)[None, :, :], required_t, axis=0)
    object_translation = np.zeros((required_t, 3), dtype=np.float32)

    # Tiny deterministic motion prevents every frame from being byte-identical while staying stable.
    for frame in range(required_t):
        theta = 0.002 * np.sin((frame + episode) / 24.0)
        object_rotation[frame] = rotation_z(theta).astype(np.float32)
        object_translation[frame] = np.array(
            [0.01 * np.sin(frame / 60.0 + episode), 0.0, 0.45 + 0.005 * np.cos(frame / 80.0)],
            dtype=np.float32,
        )

    np.savez_compressed(
        out_dir / f"episode_{episode:06d}.npz",
        pose=pose,
        scales=scales,
        shape=shape,
        object_rotation=object_rotation,
        object_translation=object_translation,
        object_scale=np.array(1.0, dtype=np.float32),
    )
    make_lumpy_mesh(episode).export(out_dir / f"episode_{episode:06d}_object.obj")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--manifest",
        type=Path,
        default=Path("manifests/track1_required_episodes.json"),
        help="Track 1 episode manifest extracted from the sample submission.",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("../v2d-challenge/generated/track1_format_baseline"),
        help="Output directory for episode npz files and object meshes.",
    )
    args = parser.parse_args()

    manifest = json.loads(args.manifest.read_text())
    args.out.mkdir(parents=True, exist_ok=True)

    for item in manifest["episodes"]:
        write_episode(args.out, int(item["episode"]), int(item["max_required_T"]))

    readme = args.out / "README.md"
    readme.write_text(
        "# Track 1 format baseline outputs\n\n"
        "Generated by `scripts/generate_track1_format_baseline.py`. These files are "
        "for validating the V2D Track 1 submission pipeline only. They are neutral, "
        "deterministic placeholder reconstructions, not model predictions.\n",
        encoding="utf-8",
    )
    print(f"wrote {len(manifest['episodes'])} episodes to {args.out}")


if __name__ == "__main__":
    main()
